-- =====================================================
-- 4. SUBMIT TEST RESULT
-- =====================================================
-- This function verifies the student credentials again.
-- It does not trust a student_id sent by the browser.
--
-- Points rule:
-- Each correct answer = 1 point.
--
-- The password is checked using the existing password_hash.
-- =====================================================

CREATE OR REPLACE FUNCTION public.taki_submit_test_result(

    p_student_number TEXT,

    p_password TEXT,

    p_subject TEXT,

    p_part TEXT,

    p_score INTEGER,

    p_total_questions INTEGER,

    p_correct_answers INTEGER,

    p_wrong_answers INTEGER,

    p_duration_seconds INTEGER

)
RETURNS JSONB

LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions

AS $$

DECLARE

    v_student public.students%ROWTYPE;

    v_points INTEGER;

    v_new_points INTEGER;

    v_new_level INTEGER;

BEGIN

    -- Validate input

    IF p_student_number IS NULL OR p_password IS NULL THEN
        RAISE EXCEPTION 'بيانات تسجيل الدخول مطلوبة';
    END IF;

    IF p_total_questions < 0
       OR p_correct_answers < 0
       OR p_wrong_answers < 0
       OR p_duration_seconds < 0 THEN

        RAISE EXCEPTION 'قيم الاختبار غير صحيحة';

    END IF;

    IF p_correct_answers + p_wrong_answers <> p_total_questions THEN
        RAISE EXCEPTION 'عدد الإجابات غير متطابق';
    END IF;


    -- Find and verify student

    SELECT *
    INTO v_student

    FROM public.students AS s

    WHERE s.student_number = p_student_number

      AND s.password_hash =
          extensions.crypt(p_password, s.password_hash)

    FOR UPDATE;


    IF NOT FOUND THEN
        RAISE EXCEPTION 'بيانات الطالب غير صحيحة';
    END IF;


    -- Calculate points

    v_points := p_correct_answers;


    -- Update student statistics

    UPDATE public.students

    SET

        points = COALESCE(points, 0) + v_points,

        tests_count = COALESCE(tests_count, 0) + 1,

        correct_answers =
            COALESCE(correct_answers, 0) + p_correct_answers,

        wrong_answers =
            COALESCE(wrong_answers, 0) + p_wrong_answers,

        level =
            GREATEST(
                1,
                FLOOR(
                    (COALESCE(points, 0) + v_points) / 100.0
                )::INTEGER + 1
            )

    WHERE id = v_student.id

    RETURNING points, level
    INTO v_new_points, v_new_level;


    -- Save test result

    INSERT INTO public.test_results (

        student_id,

        subject,

        part,

        score,

        total_questions,

        correct_answers,

        wrong_answers,

        duration_seconds

    )

    VALUES (

        v_student.id,

        COALESCE(p_subject, 'عام'),

        COALESCE(p_part, ''),

        p_score,

        p_total_questions,

        p_correct_answers,

        p_wrong_answers,

        p_duration_seconds

    );


    -- Return updated student information

    RETURN jsonb_build_object(

        'success', TRUE,

        'points_added', v_points,

        'points', v_new_points,

        'level', v_new_level,

        'tests_count',
            COALESCE(v_student.tests_count, 0) + 1,

        'correct_answers',
            COALESCE(v_student.correct_answers, 0)
            + p_correct_answers,

        'wrong_answers',
            COALESCE(v_student.wrong_answers, 0)
            + p_wrong_answers

    );

END;

$$;


-- =====================================================
-- 5. GET RANKING
-- =====================================================

CREATE OR REPLACE FUNCTION public.taki_get_ranking()

RETURNS TABLE (

    student_number TEXT,

    name TEXT,

    specialization TEXT,

    points INTEGER,

    level INTEGER,

    tests_count INTEGER

)

LANGUAGE SQL

SECURITY DEFINER

SET search_path = public

AS $$

    SELECT

        s.student_number,

        s.name,

        s.specialization,

        COALESCE(s.points, 0)::INTEGER,

        COALESCE(s.level, 1)::INTEGER,

        COALESCE(s.tests_count, 0)::INTEGER

    FROM public.students AS s

    ORDER BY

        COALESCE(s.points, 0) DESC,

        COALESCE(s.tests_count, 0) DESC,

        s.name ASC

    LIMIT 100;

$$;


